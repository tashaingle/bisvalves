// Copies the catalogue PDFs from "PDFS NEW/BiS PDFs" into public/datasheets
// and writes src/lib/datasheets.ts, which the site reads.
//
//   node scripts/sync-datasheets.mjs
//
// Re-run it whenever the PDFs are updated. Files listed in DRAFTS are left
// off the site until BiS supplies the missing figures.

import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const srcDir = path.join(root, "PDFS NEW", "BiS PDFs");
const outDir = path.join(root, "public", "datasheets");
const dataFile = path.join(root, "src", "lib", "datasheets.ts");

// Datasheets that still contain "?" in place of real figures (see qa-scan.json).
const DRAFTS = new Set([
  "2/2AS25", "2/2AS50", "2/3AS50", "2/5AS25", "2-3DS37", "2/3DS20/25",
  "2/3EPS25", "2/3EPS50", "2/3EPS100", "2/3EPSC25", "2/3EPSC50", "2/3EPSC100",
  "2/3PS25", "2/3PS50", "2/3PS100",
  "CS20", "HS25", "HTS25", "SF50", "SVA12", "SVT12", "UL75",
]);

// Catalogue pages that aren't useful on the website: covers, contact pages,
// internal index tabs and indexes whose page numbers are still "??".
const SKIP = /^(.* - Page [12]|Index Tabs & Alphanumeric|Product Index)$/;

// The same general pages appear in every section; publish one copy of each.
const GENERAL = {
  "Relief - Page 31/32": "Terms and conditions of sale",
  "Relief - Page 4": "Application notes",
  "Relief - Page 33": "Product range descriptions",
};
const GENERAL_DUPLICATE = /- ?Page (4|31\/32|33|36\/37|38)$/;

const SECTION_PAGES = {
  "Check and Shuttle - Page 3": "check-shuttle-valves",
  "Excess Flow - Page 3": "excess-flow-valves",
  "Relief - Page 3": "relief-valves",
  "Stop & Metering - Page 3": "stop-metering-valves",
  "Solenoid - Overview": "solenoid-valves",
  "4 Port Directional - Overview": "directional-control-valves",
  "Actuators - Overview": "actuators",
  "Filters - Overview": "filters",
  "Pilot operated check - Overview": "pilot-operated-check-valves",
  "Pressure Sensing - Overview": "pressure-sensing-valves",
  "Pumps - Overview": "pumps",
};

// Model code prefix -> site category, checked in order.
const FAMILIES = [
  [/^2[/-][235](AS|DS|EPSC?|PS)|^CS20$/, "solenoid-valves"],
  [/^(4R|S-6B)/, "directional-control-valves"],
  [/^(A[1-4]|H[013]|C[01]|STEX1|HC|KC|SW|L & DL)$/, "actuators"],
  [/^(3SV)/, "pressure-sensing-valves"],
  [/^(SVA|SVT|V1|M1|MS|UL|B1|2XPC)/, "pilot-operated-check-valves"],
  [/^(NR|CC|CV|YV|SV|C\d)/, "check-shuttle-valves"],
  [/^(R\d|ER)/, "excess-flow-valves"],
  [/^(EF|F\d|DF|SF)/, "filters"],
  [/^\d+PR$/, "pumps"],
  [/^(BS|S\d|TS|SM|RL|PRV|HS|HTS)/, "relief-valves"],
  [/^(BNV|MF|FMF|VFMF|XFMF|CVFMF|CMF|IMC|PCFR)/, "stop-metering-valves"],
];

const slugify = (s) =>
  s
    .toLowerCase()
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(outDir, { recursive: true });

const entries = [];
const skipped = [];
for (const file of fs.readdirSync(srcDir).filter((f) => f.endsWith(".pdf")).sort()) {
  // InDesign exports from a Mac use U+F022 where the filename had "/".
  const name = file.replace(/\.pdf$/, "").replace(//g, "/");

  let entry;
  if (SKIP.test(name)) {
    skipped.push(`${name} (catalogue page)`);
    continue;
  } else if (GENERAL[name]) {
    entry = { kind: "general", title: GENERAL[name], category: null };
  } else if (GENERAL_DUPLICATE.test(name)) {
    continue;
  } else if (SECTION_PAGES[name]) {
    entry = { kind: "overview", title: "Range overview", category: SECTION_PAGES[name] };
  } else if (DRAFTS.has(name)) {
    skipped.push(`${name} (missing figures)`);
    continue;
  } else {
    const family = FAMILIES.find(([re]) => re.test(name));
    if (!family) {
      skipped.push(`${name} (no product family)`);
      continue;
    }
    entry = { kind: "datasheet", code: name, title: `${name} datasheet`, category: family[1] };
  }

  const out = `${slugify(name)}.pdf`;
  fs.copyFileSync(path.join(srcDir, file), path.join(outDir, out));
  const bytes = fs.statSync(path.join(outDir, out)).size;
  entries.push({ ...entry, href: `/datasheets/${out}`, sizeKb: Math.round(bytes / 1024) });
}

// Natural order, so BNV25 comes before BNV25-G and F25 before F100.
const collator = new Intl.Collator("en", { numeric: true });
entries.sort((x, y) => collator.compare(x.code ?? x.title, y.code ?? y.title));

fs.writeFileSync(
  dataFile,
  `// Generated by scripts/sync-datasheets.mjs. Do not edit by hand.

export type Datasheet = {
  kind: "datasheet" | "overview" | "general";
  title: string;
  code?: string;
  category: string | null;
  href: string;
  sizeKb: number;
};

export const datasheets: Datasheet[] = ${JSON.stringify(entries, null, 2)};
`,
);

console.log(`Published ${entries.length} PDFs to public/datasheets.`);
console.log(`Left off the site (${skipped.length}):\n  ${skipped.join("\n  ")}`);
